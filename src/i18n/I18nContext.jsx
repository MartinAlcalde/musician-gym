export const translations = { en, es }

export function translate(locale, key, variables = {}) {
  const template = translations[locale]?.[key] ?? translations.en[key] ?? key
  return String(template).replace(/\{(\w+)\}/g, (_, name) => String(variables[name] ?? `{${name}}`))
}

function getInitialLocale() {
  try {
    const saved = localStorage.getItem(LANGUAGE_STORAGE_KEY)
    if (saved === 'en' || saved === 'es') return saved
  } catch {
    // Storage may be unavailable in privacy mode.
  }
  return globalThis.navigator?.language?.toLowerCase().startsWith('es') ? 'es' : 'en'
}

const defaultContext = {
  locale: 'en',
  setLocale: () => {},
  t: (key, variables) => translate('en', key, variables),
  speechLocale: 'en-US'
}

const I18nContext = createContext(defaultContext)

export function I18nProvider({ children }) {
  const [locale, setLocaleState] = useState(getInitialLocale)
  const setLocale = useCallback(nextLocale => {
    const safeLocale = nextLocale === 'es' ? 'es' : 'en'
    setLocaleState(safeLocale)
    try {
      localStorage.setItem(LANGUAGE_STORAGE_KEY, safeLocale)
    } catch {
      // The selected language still applies for this session.
    }
  }, [])
  const t = useCallback((key, variables) => translate(locale, key, variables), [locale])

  useEffect(() => {
    document.documentElement.lang = locale
    const description = document.querySelector('meta[name="description"]')
    if (description) description.setAttribute('content', t('meta.description'))
  }, [locale, t])

  const value = useMemo(() => ({
    locale,
    setLocale,
    t,
    speechLocale: locale === 'es' ? 'es-UY' : 'en-US'
  }), [locale, setLocale, t])

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export const useI18n = () => useContext(I18nContext)
